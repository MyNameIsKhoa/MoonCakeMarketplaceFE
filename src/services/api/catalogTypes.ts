/**
 * Catalog & Store service contract (TV2) — mirrors the backend DTOs exactly.
 * Source of truth: CatalogStoreService dto/request, dto/response and
 * MoonCakeMarketplaceBE/CatalogStoreService/docs/TV2_TODO.md section 3.1.
 *
 * These are wire types. Pages keep using the UI view models in `src/types.ts`;
 * map between them in the page/adapter layer. IDs are numbers, money is a JSON number (VND),
 * date-times are UTC ISO strings without offset (e.g. "2026-09-01T00:00:00").
 */
import type { Money, PromotionRuleType } from '../../types';

// ---------------------------------------------------------------------------
// Shared
// ---------------------------------------------------------------------------

/** MSS pagination: page starts at 0, size defaults to 20, max 100 (larger → 400). */
export interface PageResponse<T> {
  items: T[];
  page: number;
  size: number;
  totalElements: number;
  totalPages: number;
}

/** sort format: "field" or "field,asc|desc"; allowed fields differ per endpoint (unknown → 400). */
export interface PageQuery {
  page?: number;
  size?: number;
  sort?: string;
}

export type CategoryStatus = 'ACTIVE' | 'INACTIVE';
/** Product and variant share this status set. OUT_OF_STOCK cannot be set manually. */
export type ProductStatus = 'DRAFT' | 'ACTIVE' | 'INACTIVE' | 'OUT_OF_STOCK';
/** EXPIRED cannot be set manually; ended promotions are simply hidden from public lists. */
export type PromotionStatus = 'DRAFT' | 'ACTIVE' | 'EXPIRED' | 'DISABLED';

// ---------------------------------------------------------------------------
// Store — read public (ACTIVE only; owner also sees DRAFT/INACTIVE), write by supplier owner
// ---------------------------------------------------------------------------

export type StoreStatus = 'DRAFT' | 'ACTIVE' | 'INACTIVE' | 'SUSPENDED';
export type StoreBranchStatus = 'ACTIVE' | 'INACTIVE';

export interface StoreResponse {
  storeId: number;
  supplierIdRef: number;
  storeCode: string;
  name: string;
  slug: string;
  logoUrl: string | null;
  bannerUrl: string | null;
  themeKey: string | null;
  status: StoreStatus;
  description: string | null;
  /** Null until the seller configures a flat shipping fee; checkout must reject that state. */
  shippingFee: Money | null;
}

export interface StoreQuery {
  /** true = stores of the logged-in supplier, any status (requires login). */
  mine?: boolean;
  supplierId?: number;
}

/** storeCode and slug are generated by the server. New stores start as DRAFT. */
export interface CreateStoreRequest {
  name: string;
  logoUrl?: string;
  bannerUrl?: string;
  themeKey?: string;
  /** Max 2000 chars. */
  description?: string;
}

/**
 * Omitted/null fields keep their current value.
 * Status transitions: DRAFT → ACTIVE/INACTIVE, ACTIVE ↔ INACTIVE; SUSPENDED is admin only.
 */
export interface UpdateStoreRequest {
  name?: string;
  logoUrl?: string;
  bannerUrl?: string;
  themeKey?: string;
  status?: StoreStatus;
  description?: string;
  shippingFee?: Money;
}

/** Primary branch first, then creation order. Public viewers get ACTIVE branches only. */
export interface StoreBranchResponse {
  branchId: number;
  storeId: number;
  name: string;
  addressLine: string;
  ward: string | null;
  district: string | null;
  city: string;
  phone: string | null;
  /** Free text, e.g. "08:00–21:00". */
  openingHours: string | null;
  primary: boolean;
  status: StoreBranchStatus;
}

/**
 * The first branch of a store always becomes primary. primary=true on another branch
 * moves the flag (a store has at most one primary branch).
 */
export interface CreateStoreBranchRequest {
  name: string;
  addressLine: string;
  ward?: string;
  district?: string;
  city: string;
  phone?: string;
  openingHours?: string;
  primary?: boolean;
}

/** Omitted/null fields keep their current value. */
export interface UpdateStoreBranchRequest {
  name?: string;
  addressLine?: string;
  ward?: string;
  district?: string;
  city?: string;
  phone?: string;
  openingHours?: string;
  primary?: boolean;
  status?: StoreBranchStatus;
}

// ---------------------------------------------------------------------------
// Category (CA01–CA04) — read public, write ROLE_ADMIN only
// ---------------------------------------------------------------------------

export interface CategoryResponse {
  categoryId: number;
  parentCategoryId: number | null;
  name: string;
  slug: string;
  status: CategoryStatus;
}

export interface CategoryQuery extends PageQuery {
  /** Omit for root categories. Sort fields: name, slug, id. */
  parentCategoryId?: number;
}

export interface CreateCategoryRequest {
  name: string;
  /** a-z, 0-9 and "-" only, e.g. "banh-deo". */
  slug: string;
  parentCategoryId?: number;
}

/** Omitted/null fields keep their current value. */
export interface UpdateCategoryRequest {
  name?: string;
  slug?: string;
  parentCategoryId?: number;
  status?: CategoryStatus;
}

// ---------------------------------------------------------------------------
// Product (CA06–CA09) — read public (owner also sees drafts), write by store owner
// ---------------------------------------------------------------------------

export interface ProductSummaryResponse {
  productId: number;
  storeId: number;
  categoryId: number;
  productCode: string;
  name: string;
  status: ProductStatus;
  /** Lowest price among ACTIVE variants; null when the product has no ACTIVE variant. */
  minPrice: Money | null;
  /** First ACTIVE variant image; null when none. */
  imageUrl: string | null;
}

export interface ProductResponse {
  productId: number;
  storeId: number;
  categoryId: number;
  productCode: string;
  name: string;
  description: string | null;
  status: ProductStatus;
  createdAt: string;
  updatedAt: string;
  /** Public viewers get ACTIVE variants only; the store owner gets all. */
  variants: VariantResponse[];
}

export interface ProductQuery extends PageQuery {
  q?: string;
  storeId?: number;
  categoryId?: number;
  /** true = products of the logged-in supplier's stores, any status (requires login). */
  mine?: boolean;
  // Sort fields: name, createdAt, id. Default createdAt,desc.
}

/** productCode is generated by the server; price lives on variants. New products start as DRAFT. */
export interface CreateProductRequest {
  storeId: number;
  categoryId: number;
  name: string;
  description?: string;
}

/**
 * Status transitions: DRAFT → ACTIVE/INACTIVE, ACTIVE ↔ INACTIVE (never back to DRAFT).
 * ACTIVE requires at least one ACTIVE variant (otherwise 400).
 */
export interface UpdateProductRequest {
  categoryId?: number;
  name?: string;
  description?: string;
  status?: Exclude<ProductStatus, 'OUT_OF_STOCK'>;
}

// ---------------------------------------------------------------------------
// Variant (CA11–CA14)
// ---------------------------------------------------------------------------

export interface VariantResponse {
  variantId: number;
  productId: number;
  sku: string;
  variantName: string;
  imageUrl: string | null;
  basePrice: Money;
  stockQuantity: number;
  status: ProductStatus;
}

/** New variants start as DRAFT. Duplicate SKU → 409. */
export interface CreateVariantRequest {
  sku: string;
  variantName: string;
  imageUrl?: string;
  basePrice: Money;
  stockQuantity: number;
}

/**
 * stockQuantity below the quantity currently held by checkouts → 409.
 * Deactivating the last ACTIVE variant of an ACTIVE product → 400.
 */
export interface UpdateVariantRequest {
  sku?: string;
  variantName?: string;
  imageUrl?: string;
  basePrice?: Money;
  stockQuantity?: number;
  status?: Exclude<ProductStatus, 'OUT_OF_STOCK'>;
}

// ---------------------------------------------------------------------------
// Promotion (CA16–CA20)
// ---------------------------------------------------------------------------

export interface PromotionRuleResponse {
  promotionRuleId: number;
  ruleType: PromotionRuleType;
  targetVariantId: number | null;
  rewardVariantId: number | null;
  minQuantity: number | null;
  discountPercent: number | null;
  discountAmount: Money | null;
  rewardQuantity: number | null;
}

export interface PromotionResponse {
  promotionId: number;
  storeId: number;
  name: string;
  startAt: string;
  endAt: string;
  status: PromotionStatus;
  rules: PromotionRuleResponse[];
}

export interface PromotionQuery extends PageQuery {
  storeId?: number;
  /** true = promotions of the logged-in supplier's stores, any status (requires login). */
  mine?: boolean;
  // Sort fields: startAt, endAt, name, id. Default startAt,desc.
}

/**
 * Required fields per ruleType (fields of other types must be omitted, otherwise 400):
 * - PERCENT_DISCOUNT: discountPercent in (0, 100]; targetVariantId optional (omit = every line of the store)
 * - FIXED_DISCOUNT:   discountAmount > 0; targetVariantId optional (omit = whole store order)
 * - BUY_X_GET_Y:      targetVariantId, rewardVariantId, minQuantity (X), rewardQuantity (Y)
 * Target/reward variants must belong to the promotion's store.
 */
export interface PromotionRuleRequest {
  ruleType: PromotionRuleType;
  targetVariantId?: number;
  rewardVariantId?: number;
  minQuantity?: number;
  discountPercent?: number;
  discountAmount?: Money;
  rewardQuantity?: number;
}

/** startAt < endAt (UTC). 1–20 rules. New promotions start as DRAFT. */
export interface CreatePromotionRequest {
  storeId: number;
  name: string;
  startAt: string;
  endAt: string;
  rules: PromotionRuleRequest[];
}

/** Transitions: DRAFT → ACTIVE/DISABLED, ACTIVE ↔ DISABLED; an ended promotion cannot be activated. */
export interface UpdatePromotionRequest {
  name?: string;
  startAt?: string;
  endAt?: string;
  status?: Exclude<PromotionStatus, 'EXPIRED'>;
}
